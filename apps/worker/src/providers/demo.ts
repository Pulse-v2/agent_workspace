import {
  type AgentAction, type AgentPlan, type FinalAnswer, type FinalAnswerInput, type LLMProvider,
  type PlanInput, type ProviderResult, type StepInput,
} from "./types.js";

export const DEMO_MODEL = "demo-deterministic";
const DEMO_NOTICE = "_Generated by the deterministic demo provider (no AI model). It only restates tool results and retrieved excerpts._";

function result<T>(value: T): ProviderResult<T> {
  return { value, usage: { inputTokens: 0, outputTokens: 0, model: DEMO_MODEL } };
}

const toolCall = (name: string, args: unknown, type: AgentAction["type"] = "tool_call"): AgentAction =>
  ({ type, tool_name: name, arguments_json: JSON.stringify(args), answer: null });

/**
 * Deterministic provider for running the app without a paid API key. It does
 * not call a model. Fixed policy: search sources, summarize the first CSV
 * dataset if there is one, save a report when the task asks for one (which
 * exercises the approval workflow), then answer. Runs are recorded with model
 * "demo-deterministic" so they are never presented as real AI execution.
 */
export class DemoProvider implements LLMProvider {
  readonly name = "demo";
  readonly model = DEMO_MODEL;
  readonly isDemo = true;

  async generatePlan(input: PlanInput) {
    const wantsReport = /\b(report|save)\b/i.test(input.objective);
    return result<AgentPlan>({
      summary: "Search this workspace’s indexed sources, analyze available datasets, then provide a sourced answer.",
      steps: [
        { title: "Search workspace sources", description: "Find indexed excerpts relevant to the task." },
        { title: "Analyze datasets", description: "Summarize CSV datasets in the workspace, if any." },
        ...(wantsReport ? [{ title: "Save report", description: "Prepare a Markdown report and request approval to save it." }] : []),
        { title: "Prepare a sourced answer", description: "Summarize what the tool results and source excerpts support." },
      ],
    });
  }

  async executeStep(input: StepInput) {
    const attempts = (name: string) => input.completedSteps.filter((step) => step.tool_name === name);
    const searches = attempts("search_documents");
    if (!searches.some((step) => step.status === "completed") && searches.length < 2) {
      return result(toolCall("search_documents", { query: input.objective, top_k: 6 }));
    }
    const dataset = input.documents.find((document) => document.is_csv);
    if (dataset && attempts("analyze_csv").length === 0) {
      return result(toolCall("analyze_csv", { operation: "summary", document_id: dataset.id }));
    }
    if (/\b(report|save)\b/i.test(input.objective) && attempts("save_report").length === 0) {
      return result(toolCall("save_report", {
        title: `Report: ${input.objective.slice(0, 120)}`,
        content_markdown: buildReport(input),
        source_chunk_ids: input.evidence.slice(0, 3).map((item) => item.chunk_id),
      }, "approval_request"));
    }
    const answer = input.evidence.length || input.completedSteps.some((step) => step.status === "completed" && step.tool_name === "analyze_csv")
      ? "The workspace tools returned the results summarized below."
      : "I could not verify this from the indexed sources available in this workspace.";
    return result<AgentAction>({ type: "final_answer", tool_name: null, arguments_json: null, answer });
  }

  async generateFinalAnswer(input: FinalAnswerInput) {
    const citations = input.evidence.slice(0, 3).map((item) => ({ chunk_id: item.chunk_id, quote: item.content.slice(0, 400) }));
    const findings = input.completedSteps.filter((step) => step.status !== "failed").map((step) => `- **${step.title}:** ${step.summary.slice(0, 400)}`);
    const answer = [input.draftAnswer, findings.length ? `\n${findings.join("\n")}` : "", `\n${DEMO_NOTICE}`].join("\n");
    return result<FinalAnswer>({ answer, citations });
  }

  async generateEmbeddings(): Promise<ProviderResult<number[][]>> {
    throw new Error("The demo provider does not create embeddings. Configure an embedding API key to enable semantic indexing.");
  }
}

function buildReport(input: StepInput) {
  const findings = input.completedSteps.filter((step) => step.status === "completed").map((step) => `- **${step.title}:** ${step.summary.slice(0, 600)}`);
  const sources = [...new Set(input.evidence.map((item) => item.file_name))].map((name) => `- ${name}`);
  return [
    `# ${input.objective.slice(0, 150)}`,
    "",
    "## Findings",
    findings.length ? findings.join("\n") : "- No tool results were available.",
    "",
    "## Sources",
    sources.length ? sources.join("\n") : "- No document excerpts were retrieved.",
    "",
    DEMO_NOTICE,
  ].join("\n");
}
